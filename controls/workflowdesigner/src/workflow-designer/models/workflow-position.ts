/**
 * Defines the position of a workflow item on the Workflow Designer canvas.
 */
export interface WorkflowPosition {
    /**
     * Defines the horizontal position of the workflow item.
     *
     * @default 0
     */
    x?: number;

    /**
     * Defines the vertical position of the workflow item.
     *
     * @default 0
     */
    y?: number;
}
