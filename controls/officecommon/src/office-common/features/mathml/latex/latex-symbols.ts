/**
 * Returns the LaTeX command for a Unicode symbol (compression `GetSymbolLaTeX`), or undefined.
 * `l` maps to `\\ell` only for the script font.
 *
 * @param {string} char - The char.
 * @param {boolean} isScriptFont - The is script font.
 * @returns {string | undefined} The result.
 * @private
 */
export function getSymbolLatex(char: string, isScriptFont: boolean): string | undefined {
    const code: number = char.charCodeAt(0);
    if (code === 108) {
        return isScriptFont ? '\\ell' : undefined;
    }
    return ownValue<string>(UNICODE_TO_LATEX, code);
}
