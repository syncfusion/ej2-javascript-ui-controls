/**
 * Returns the Unicode symbol for a LaTeX command, or the input unchanged when unknown.
 *
 * @param {string} latex - The latex.
 * @returns {string} The result.
 * @private
 */
export function getLatexSymbol(latex: string): string {
    const symbol: string | undefined = ownValue<string>(LATEX_SYMBOLS, latex);
    return symbol !== undefined ? symbol : latex;
}

